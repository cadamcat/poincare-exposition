#!/usr/bin/env python3
"""Real Lean material for chapter 8, as text: writes scenes/c8/leantext.js.

Usage: lean_text.py TARGET_FILE FORK_DIR
  TARGET_FILE  YPoincare_poincare_conjecture.lean (mathdb-lean/problems 26876961, Apache-2.0)
  FORK_DIR     the differential-geometry-mathdb checkout at 9f65eaf9 (Apache-2.0)
window.LEAN_TARGET      the definition of ConjectureFor and of Target, verbatim;
window.LEAN_SUBMISSION  the theorem Submission.solution with its proof, verbatim;
window.LEAN_AXIOMS      the axiom report line for Submission.solution from verification/native-target-axioms.log.
All three are copied verbatim; the scene only lays them out."""
import hashlib, json, sys
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / 'scenes' / 'c8' / 'leantext.js'
TARGET_SHA = '9609b79bd21353e74225bf0e87777ec0a5da6ba3448846fd0ee07b531a596d91'


def block(lines, start, stop):
    i = next(k for k, l in enumerate(lines) if l.startswith(start))
    j = next(k for k in range(i, len(lines)) if lines[k].startswith(stop))
    return lines[i:j + 1]


def main():
    target, fork = Path(sys.argv[1]), Path(sys.argv[2])
    assert hashlib.sha256(target.read_bytes()).hexdigest() == TARGET_SHA
    t = target.read_text().split('\n')
    conj = block(t, 'def ConjectureFor', '  ∀ (M : Type)')
    tgt = block(t, 'abbrev Target', '    ConjectureFor 3')
    sub = block((fork / 'Submission.lean').read_text().split('\n'), 'theorem solution', '  exact ')
    ax = [l for l in (fork / 'verification' / 'native-target-axioms.log').read_text().split('\n')
          if l.startswith("'Submission.solution' depends on axioms")]
    assert len(ax) == 1, ax
    js = lambda v: json.dumps(v, ensure_ascii=False, indent=1)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text('/* Generated by tools/lean_text.py: mathdb-lean/problems 26876961 (statement) and\n'
                   '   differential-geometry-mathdb 9f65eaf9 (proof, axiom report), both Apache-2.0. */\n'
                   f'window.LEAN_TARGET = {js(conj + [""] + tgt)};\n'
                   f'window.LEAN_SUBMISSION = {js(sub)};\n'
                   f'window.LEAN_AXIOMS = {js(ax)};\n')
    print(f'{len(conj) + len(tgt)} statement lines, {len(sub)} proof lines, axiom line: {ax[0]}')


if __name__ == '__main__':
    main()
